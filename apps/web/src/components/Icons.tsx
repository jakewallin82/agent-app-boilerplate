// Helper to get file icon based on type
export function getFileIcon(fileType: string, size = 14) {
  switch (fileType) {
    case 'md':
      return <FileTextIcon size={size} className="text-blue-400" />;
    case 'json':
      return <FileJsonIcon size={size} className="text-yellow-400" />;
    case 'csv':
      return <FileSpreadsheetIcon size={size} className="text-green-400" />;
    default:
      return <FileIcon size={size} className="text-muted-foreground" />;
  }
}
